# Cloud computing 101

# Cloud computing is a model for delivering computing resources over the internet. 
# It allows users to access and use shared resources, such as servers, storage, 
# databases, networking, software, and more, without having to manage the underlying infrastructure.

# It's like a virtual IT Department that provides on-demand access to computing resources, 
# enabling businesses and individuals to scale their operations quickly and efficiently.

# You can use your localhost to run applications, but if it grows too large, 
# you may need to use cloud computing to handle the increased demand.

# Benefits of cloud computing include:
# 1. Scalability: Easily scale resources up or down based on demand.
# 2. Cost-effectiveness: Pay only for the resources you use, reducing capital expenses.
# 3. Accessibility: Access resources from anywhere with an internet connection.
# 4. Collaboration: Enable teams to work together in real-time, regardless of location.
# 5. Specialized services: Access advanced services like AI, machine learning, and big data analytics without needing in-house expertise.

# Primary Cloud Service Models:
# 1.) IaaS (Infrastructure as a Service): Provides virtualized computing resources over the internet. 
# Users can rent virtual machines, storage, and networking components. 
# Used for high customization and control over the infrastructure, 
# but requires more management and maintenance.
# Examples: Amazon Web Services (AWS), Microsoft Azure, Google Cloud Platform (GCP).

# 2.) PaaS (Platform as a Service): Provides a platform that allows developers to build, 
# deploy, and manage applications without worrying about the underlying infrastructure.
# Streamlines development and deployment processes, 
# but may have limitations on customization and control.
# Best used for rapid application development and deployment, 
# especially for web and mobile applications.
# Examples: Heroku, Google App Engine, Microsoft Azure App Service.

# 3.)SaaS (Software as a Service): Delivers software applications over the internet on a subscription basis.
# Users can access the software through a web browser without needing to install or maintain it.
# Best used for applications that require frequent updates and collaboration, 
# without the need for extensive IT management.
# Examples: Google Workspace, Microsoft Office 365, Salesforce.