# Best practices for effective prompts with GenAI

# Generative Artificial Intelligence, or GenAI, 
# is a type of artificial intelligence that can create new content and ideas. 

# How does GenAI work?

# GenAI learns from massive amounts of data, identifying patterns and relationships. 
# Then, it uses this knowledge to generate new content that is similar in style 
# and structure to the data it was trained on.

# Be specific, be clear
# When crafting prompts for GenAI, it's important to be specific and clear about what you want.

# Give Examples
# Providing examples in your prompts can help GenAI 
# understand the context and generate more relevant content.

# Prompt: Write a Python function to calculate the factorial of a number, using recursion.
def countdown(n):
  if n <= 0:
    print('Blastoff!')
  else:
    print(n)
    countdown(n-1)

