# Why efficiency matters in automation

# Automation script - An automation script is a set of ​instructions written in Python that ​automates a specific task or process. 
# Organizations can leverage scripting to streamline repetitive tasks, reduce human error, and improve overall efficiency.

# Efficient writing aims for code that is not only functional but also resource conscious and maintainable.

# Effects of ineffective code:
# 1) Performance bottlenecks - causing delays in critical workflows and impact overall productivity 
# 2) Excessive use system resources - potentially affecting the performance of other applications and overall system stability
# 3) Performance Degradation - leading to slower execution times and reduced responsiveness of the automation script

# The right tools for the job: 
# Choose the right algorithms and data structures
# Minimize I/O Operations - reduce the frequency and volume of read/write operations to improve performance and reduce latency
# Avoid redundant computations - prevent unnecessary recalculations by storing and reusing results when possible
# Use built-in functions and libraries - leverage optimized and well-tested functions provided by Python to improve performance and reduce development time

